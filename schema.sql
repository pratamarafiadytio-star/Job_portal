-- 1. Buat Tabel jobs jika belum ada
CREATE TABLE IF NOT EXISTS public.jobs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    company_name TEXT NOT NULL,
    category TEXT NOT NULL DEFAULT 'Lainnya',
    job_type TEXT NOT NULL DEFAULT 'Full Time',
    location TEXT NOT NULL DEFAULT 'Indonesia',
    salary_display TEXT DEFAULT 'Kompetitif',
    experience_level TEXT DEFAULT 'Semua Tingkat',
    poster_image TEXT DEFAULT '',
    description TEXT NOT NULL,
    requirements JSONB DEFAULT '[]'::jsonb,
    responsibilities JSONB DEFAULT '[]'::jsonb,
    benefits JSONB DEFAULT '[]'::jsonb,
    whatsapp TEXT DEFAULT '',
    email TEXT DEFAULT '',
    website_url TEXT DEFAULT '',
    contact_type TEXT DEFAULT 'whatsapp',
    contact_value TEXT DEFAULT '',
    deadline TEXT DEFAULT '',
    status TEXT DEFAULT 'active',
    is_featured BOOLEAN DEFAULT false,
    views_count INT DEFAULT 0,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Script Migrasi Tambahan jika tabel sudah terlanjur ada:
ALTER TABLE public.jobs ADD COLUMN IF NOT EXISTS whatsapp TEXT DEFAULT '';
ALTER TABLE public.jobs ADD COLUMN IF NOT EXISTS email TEXT DEFAULT '';
ALTER TABLE public.jobs ADD COLUMN IF NOT EXISTS website_url TEXT DEFAULT '';

-- 2. Buat Index untuk pencarian dan filter cepat
CREATE INDEX IF NOT EXISTS idx_jobs_status ON public.jobs (status);
CREATE INDEX IF NOT EXISTS idx_jobs_category ON public.jobs (category);
CREATE INDEX IF NOT EXISTS idx_jobs_created_at ON public.jobs (created_at DESC);

-- 3. Aktifkan Row Level Security (RLS)
ALTER TABLE public.jobs ENABLE ROW LEVEL SECURITY;

-- 4. Policy Keamanan:
-- Pengunjung publik hanya boleh MEMBACA (SELECT)
CREATE POLICY "Public Read Access"
ON public.jobs
FOR SELECT
USING (true);

-- Admin / API key boleh INSERT, UPDATE, DELETE
CREATE POLICY "Enable Full Access for API"
ON public.jobs
FOR ALL
USING (true)
WITH CHECK (true);

